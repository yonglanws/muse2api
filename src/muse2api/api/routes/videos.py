router = APIRouter(tags=["videos"], dependencies=[Depends(require_api_key)])

# OpenAI's Sora aliases are accepted for wire compatibility and mapped to the
# gateway's only video model; the response echoes the requested name.
_SORA_PREFIX = "sora-"

_SIZE_HINTS = {
    "720x1280": "9:16",
    "1280x720": "16:9",
    "1024x1792": "4:7",
    "1792x1024": "7:4",
}
_ASPECT_SIZES = {
    "9:16": "720x1280",
    "16:9": "1280x720",
    "4:7": "1024x1792",
    "7:4": "1792x1024",
    "1:1": "1024x1024",
    "4:3": "1280x960",
    "3:4": "960x1280",
}
_DEFAULT_SIZE = "720x1280"
_DEFAULT_SECONDS = 4


def _resolve_video_model(name: str | None):
    if not name or name == "muse-video":
        return MODELS["muse-video"]
    if name.strip().lower().startswith(_SORA_PREFIX):
        return MODELS["muse-video"]
    raise NotFound(
        f"The model '{name}' does not exist or you do not have access to it.",
        param="model", code="model_not_found")


def _normalize_size(raw: Any) -> str:
    if raw is None or raw == "":
        return _DEFAULT_SIZE
    if isinstance(raw, str) and raw.strip():
        value = raw.strip()
        if value in _SIZE_HINTS:
            return value
        if value in _ASPECT_SIZES:
            return _ASPECT_SIZES[value]
        # Accept e.g. "1280×720" and case-insensitive values.
        normalized = value.lower().replace("×", "x").replace(" ", "")
        if normalized in _SIZE_HINTS:
            return normalized
    raise InvalidRequest(
        "size must be one of 720x1280, 1280x720, 1024x1792, 1792x1024",
        param="size")


def _size_hint(size: str) -> str:
    return _SIZE_HINTS.get(size, size)


def _parse_seconds(*values: Any) -> int:
    for value in values:
        if value is None or value == "":
            continue
        try:
            seconds = int(str(value).strip())
        except (TypeError, ValueError):
            raise InvalidRequest(
                "seconds must be an integer between 1 and 60",
                param="seconds") from None
        if 1 <= seconds <= 60:
            return seconds
        raise InvalidRequest("seconds must be between 1 and 60", param="seconds")
    return _DEFAULT_SECONDS


async def _load_reference(value: Any, svc: Services,
                          owner: str | None = None) -> InputImage | None:
    """Resolve an ``input_reference`` (file, file_id, URL, data URL, base64)."""
    if value is None or value == "":
        return None
    if isinstance(value, UploadFile):
        data = await value.read()
        if svc.settings.file_max_bytes and len(data) > svc.settings.file_max_bytes:
            raise InvalidRequest("input_reference exceeds the upload limit",
                                 param="input_reference")
        mime = value.content_type or mimetypes.guess_type(value.filename or "")[0]
        mime = (mime or "image/png").split(";")[0].strip()
        if not mime.startswith("image/"):
            raise InvalidRequest("input_reference must be an image",
                                 param="input_reference")
        return InputImage(data=data, mime=mime)
    if isinstance(value, str):
        text = value.strip()
        if text.startswith("{"):
            try:
                value = json.loads(text)
            except ValueError:
                raise InvalidRequest("input_reference is not valid JSON",
                                     param="input_reference") from None
        else:
            data, mime = await load_image_ref(text)
            return InputImage(data=data, mime=mime)
    if isinstance(value, dict):
        file_id = value.get("file_id") or value.get("id")
        url = value.get("image_url") or value.get("url")
        if file_id:
            data, entry = svc.files.read(str(file_id), owner)
            mime = str(entry.get("mime") or "image/png").split(";")[0].strip()
            if not mime.startswith("image/"):
                raise InvalidRequest("input_reference must be an image",
                                     param="input_reference")
            return InputImage(data=data, mime=mime)
        if url:
            data, mime = await load_image_ref(str(url))
            return InputImage(data=data, mime=mime)
    raise InvalidRequest(
        "input_reference must be an image file, file_id, image_url or data URL",
        param="input_reference")


def _owner(request: Request, task: Task) -> bool:
    return visible(task.request.get("key_id"),
                   getattr(request.state, "key_id", None))


def _video_id(task_id: str) -> str:
    """Internal task id → Sora-shaped public id."""
    return "video_" + task_id.removeprefix("task_")


def _task_id(video_id: str) -> str:
    """Public id → internal task id (old ``task_`` ids keep working)."""
    return "task_" + video_id[6:] if video_id.startswith("video_") else video_id


def _get_video(request: Request, video_id: str, svc: Services) -> Task:
    task = svc.tasks.get(_task_id(video_id))
    if task is None or task.kind != "video" or not _owner(request, task):
        raise NotFound(f"video '{video_id}' not found", param="video_id")
    return task


def _status(task: Task) -> str:
    return {
        TaskStatus.QUEUED: "queued",
        TaskStatus.RUNNING: "in_progress",
        TaskStatus.SUCCEEDED: "completed",
        TaskStatus.FAILED: "failed",
        TaskStatus.CANCELLED: "failed",
    }.get(task.status, "failed")


def _video_view(task: Task, svc: Services) -> dict:
    result = task.result or {}
    status = _status(task)
    error = None
    if status == "failed":
        info = task.error or {}
        error = {
            "code": str(info.get("code") or "generation_failed"),
            "message": str(info.get("message") or "video generation failed"),
        }
    seconds = str(task.request.get("seconds") or _DEFAULT_SECONDS)
    size = str(task.request.get("size") or _DEFAULT_SIZE)
    expires_at = None
    completed_at = None
    if task.finished:
        completed_at = int(task.updated_at)
        if status == "completed" and svc.settings.media_retention_days > 0:
            expires_at = completed_at + int(svc.settings.media_retention_days * 86400)
    remixed_from = task.request.get("remixed_from_video_id")
    if remixed_from and str(remixed_from).startswith("task_"):
        remixed_from = _video_id(str(remixed_from))
    return {
        "id": _video_id(task.id),
        "object": "video",
        "created_at": int(task.created_at),
        "completed_at": completed_at,
        "expires_at": expires_at,
        "status": status,
        "progress": task.progress,
        "model": task.request.get("model") or "muse-video",
        "prompt": task.request.get("prompt"),
        "remixed_from_video_id": remixed_from,
        "seconds": seconds,
        "size": size,
        "error": error,
        # Legacy gateway fields (ignored by the official SDK, used by the
        # dashboard and pre-0.12 clients).
        "task_status": task.status.value,
        "result": result or None,
    }


def _submit_video(request: Request, svc: Services, *, prompt: str,
                  model_name: str, spec, seconds: int, size: str,
                  first_frame: InputImage | None,
                  remixed_from_video_id: str | None = None) -> Task:
    base = public_base(request)
    duration = seconds
    hinted_size = _size_hint(size)

    async def runner(progress) -> dict:
        req = VideoRequest(prompt=prompt, model=spec.id, size=hinted_size,
                           duration=duration, first_frame=first_frame,
                           timeout=svc.settings.video_timeout,
                           on_progress=progress)
        result = await svc.gateway.generate_video(req)
        name = svc.media.save(result.data, result.mime, prefix="vid")
        return {"url": f"{base}/v1/media/{name}", "name": name,
                "mime": result.mime, "width": result.width,
                "height": result.height}

    meta = {
        "model": model_name,
        "upstream_model": spec.id,
        "prompt": prompt,
        "seconds": str(seconds),
        "duration": duration,
        "size": size,
        "size_hint": hinted_size,
        "has_first_frame": first_frame is not None,
        "key_id": getattr(request.state, "key_id", None),
    }
    if remixed_from_video_id:
        meta["remixed_from_video_id"] = remixed_from_video_id
    task = svc.tasks.submit("video", meta, runner)
    request.state.task_id = task.id
    return task


async def _parse_create(request: Request) -> dict[str, Any]:
    ctype = request.headers.get("content-type", "")
    if ctype.startswith(("multipart/form-data", "application/x-www-form-urlencoded")):
        form = await request.form()
        fields = {k: v for k, v in form.items() if isinstance(v, str)}
        reference = form.get("input_reference")
        if reference is None:
            file_id = fields.get("input_reference[file_id]")
            image_url = fields.get("input_reference[image_url]")
            if file_id:
                reference = {"file_id": file_id}
            elif image_url:
                reference = {"image_url": image_url}
        return {
            "prompt": fields.get("prompt", ""),
            "model": fields.get("model"),
            "seconds": fields.get("seconds"),
            "size": fields.get("size"),
            "input_reference": reference,
            "image": fields.get("image"),
        }
    try:
        payload = await request.json()
    except ValueError:
        raise InvalidRequest("request body must be valid JSON") from None
    try:
        body = VideoCreateRequest.model_validate(payload)
    except ValidationError as exc:
        first = exc.errors()[0] if exc.errors() else {}
        loc = ".".join(str(part) for part in first.get("loc") or ())
        raise InvalidRequest(first.get("msg", "invalid video request"),
                             param=loc or None) from None
    return body.model_dump()


@router.post("/v1/videos")
async def create_video(request: Request, svc: Services = Depends(get_services)) -> dict:
    data = await _parse_create(request)
    prompt = str(data.get("prompt") or "").strip()
    if not prompt:
        raise InvalidRequest("prompt is required", param="prompt")
    model_name = str(data.get("model") or "muse-video").strip() or "muse-video"
    spec = _resolve_video_model(model_name)
    request.state.model = spec.id  # log the actual upstream model
    seconds = _parse_seconds(data.get("seconds"), data.get("duration"))
    size = _normalize_size(data.get("size"))
    ref = data.get("input_reference") or data.get("image")
    first_frame = await _load_reference(
        ref, svc, getattr(request.state, "key_id", None))
    task = _submit_video(request, svc, prompt=prompt, model_name=model_name,
                         spec=spec, seconds=seconds, size=size,
                         first_frame=first_frame)
    return _video_view(task, svc)


@router.get("/v1/videos")
async def list_videos(
    request: Request,
    limit: int = Query(default=20, ge=1, le=100),
    order: str = Query(default="desc", pattern="^(asc|desc)$"),
    after: str | None = Query(default=None),
    svc: Services = Depends(get_services),
) -> dict:
    current = getattr(request.state, "key_id", None)
    owner = None if current in (None, "admin") else current
    if after:
        cursor = svc.tasks.get(_task_id(after))
        if cursor is None or cursor.kind != "video" or not _owner(request, cursor):
            raise NotFound(f"video '{after}' not found", param="after")
    tasks, has_more = svc.tasks.query(kind="video", owner=owner, limit=limit,
                                      order=order,
                                      after=_task_id(after) if after else None)
    data = [_video_view(task, svc) for task in tasks]
    return {"object": "list", "data": data,
            "first_id": data[0]["id"] if data else None,
            "last_id": data[-1]["id"] if data else None,
            "has_more": has_more}


