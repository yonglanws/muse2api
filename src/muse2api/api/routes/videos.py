@router.get("/v1/videos/{video_id}/content")
async def get_video_content(
    video_id: str,
    request: Request,
    variant: str = Query(default="video"),
    svc: Services = Depends(get_services),
):
    task = _get_video(request, video_id, svc)
    if task.status != TaskStatus.SUCCEEDED:
        raise NotFound(f"video '{video_id}' has no downloadable content",
                       param="video_id")
    if variant != "video":
        raise InvalidRequest(
            f"variant '{variant}' is not produced by muse.ai",
            param="variant", code="unsupported_variant")
    result = task.result or {}
    name = str(result.get("name") or str(result.get("url") or "").rsplit("/", 1)[-1])
    return FileResponse(svc.media.path_of(name),
                        media_type=str(result.get("mime") or "video/mp4"))


@router.post("/v1/videos/{video_id}/remix")
async def remix_video(video_id: str, body: VideoRemixRequest, request: Request,
                      svc: Services = Depends(get_services)) -> dict:
    source = _get_video(request, video_id, svc)
    if source.status != TaskStatus.SUCCEEDED:
        raise InvalidRequest("only a completed video can be remixed",
                             param="video_id", code="video_not_completed")
    model_name = str(source.request.get("model") or "muse-video")
    spec = _resolve_video_model(model_name)
    request.state.model = spec.id
    task = _submit_video(
        request, svc, prompt=body.prompt, model_name=model_name, spec=spec,
        seconds=_parse_seconds(source.request.get("seconds")),
        size=_normalize_size(source.request.get("size")),
        first_frame=None, remixed_from_video_id=_video_id(source.id))
    return _video_view(task, svc)


@router.get("/v1/videos/{video_id}")
async def get_video(video_id: str, request: Request, response: Response,
                    svc: Services = Depends(get_services)) -> dict:
    task = _get_video(request, video_id, svc)
    request.state.model = task.request.get("upstream_model") or task.request.get("model")
    # The official SDK's poll() reads this header; without it it sleeps 1 s.
    response.headers["openai-poll-after-ms"] = "1000"
    return _video_view(task, svc)


@router.delete("/v1/videos/{video_id}")
async def delete_video(video_id: str, request: Request,
                       svc: Services = Depends(get_services)) -> dict:
    task = _get_video(request, video_id, svc)
    if not task.finished:
        raise InvalidRequest("video is still in progress and cannot be deleted",
                             param="video_id", code="video_not_finished")
    result = task.result or {}
    name = str(result.get("name") or str(result.get("url") or "").rsplit("/", 1)[-1])
    if name:
        svc.media.delete(name)
    svc.tasks.delete(_task_id(video_id))
    return {"id": video_id, "object": "video.deleted", "deleted": True}
