"""Videos API: OpenAI Sora-compatible shape on top of the project's task store.

The muse.ai web agent has no structured video endpoint: a video is generated by
an ordinary chat turn and returned as a ``delta.presentation``. This module
keeps the project's asynchronous task machinery but exposes the OpenAI Videos
object surface, so ``client.videos.create(...).poll()`` /
``download_content`` / ``list`` / ``delete`` / ``remix`` behave like the real
API. Capabilities the upstream agent does not have (video-to-video edits,
extensions, character cameos) return an explicit 501 rather than a fake job.
"""

